import { chromium } from "playwright";
const SITE = process.env.SITE ?? "http://localhost:3101";
const q = process.env.Q ?? "Kya sach hai ki Yamuna mein zehrile jhaag wapas aa gaye hain?";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1180, height: 1400 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text().slice(0, 200)));
await page.goto(`${SITE}/ask`, { waitUntil: "networkidle" });
await page.screenshot({ path: "/home/user/jan-drishti/shot-chat-empty.png" });
await page.locator("textarea").click();
await page.keyboard.type(q, { delay: 5 });
await page.locator('button[aria-label="Send"]').click();
const t0 = Date.now();
await page.waitForFunction(() => /\d+ models ·|\d+ मॉडल|could not be completed/.test(document.body.innerText), null, { timeout: 240000 });
console.log(`sources block after ${((Date.now() - t0) / 1000).toFixed(1)}s`);
await page.waitForTimeout(1200);
await page.screenshot({ path: "/home/user/jan-drishti/shot-chat-answer.png" });
const main = await page.innerText("main");
console.log(main.slice(0, 1500));
await browser.close();
console.log("errors:", errors.length ? errors.slice(0, 3) : "none");
